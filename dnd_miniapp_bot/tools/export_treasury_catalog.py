"""Export the exact server reward table, including per-item drop chances."""
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from app.treasury import RARITIES,POOL,FRAMES,enrich

if __name__=='__main__':
    lines=['# Сокровищница','', 'Один ключ — одно открытие аккаунтом, одна награда. Пустых результатов нет.',
           'После выбора редкости: искры 40%, золото 5%, прочие награды 55%. Внутри группы варианты равновероятны.',
           'Каждое десятое открытие: редкое 75%, эпическое 20%, легендарное 5%. Буст открытия: необычное 55%, редкое 35%, эпическое 8%, легендарное 2%.',
           'Игровые предметы передаются выбранному фэнтези-персонажу через заявку мастеру.',
           'Мастер вручную вносит предмет в игру, затем подтверждает выдачу. Отказ возвращает предмет.',
           'Одновременно допускается до пяти ожидающих заявок на сокровища.', '']
    lines += ['## Награды с выбором','',
              '- Фамильяр: обычное — угроза до 0; необычное — до 1/8; редкое — до 1/4; эпическое — до 1/2; легендарное — до 1.',
              '- Игрок указывает название существа, уровень угрозы и источник из бестиария своей кампании. Мастер проверяет запись и допустимость.',
              '- Оружие +1 (редкое), броня +1 (эпическое), оружие +2 (легендарное): игрок выбирает базовый предмет, бонус задан наградой.',
              '- Выбор не даёт дополнительных свойств именованных магических предметов. Ранее выпавшая фиксированная добыча сохраняется.', '']
    for id,name,chance in RARITIES:
        items=POOL[id]
        lines += [f'## {name} — {chance}%', '',f'Вариантов: {len(items)}. Шансы зависят от группы награды.','']
        for item in items:
            item=enrich(item)
            lines.append('- '+item['icon']+' '+item['name']+(' — '+item['note'] if item.get('note') else ''))
        lines.append('')
    lines += ['## Правила купонов','',
              '- Скидки 10%, 20%, 30%: сначала тратится наибольшая активированная скидка. Не складываются; остальные сохраняются.',
              '- При недостатке искр, повторной покупке или ошибке купон не расходуется.',
              '- Купон цвета: после активации бесплатно открывает свой цвет или одноцветный пресет выбранного эффекта.',
              '- Купон градиента: после активации бесплатно открывает свой градиент или градиентный пресет выбранного эффекта.',
              '- Право на рамку: любая уникальная рамка, в том числе за достижение. Само достижение не выдаётся.', '']
    lines += [f'- {name}: одно активированное право на рамку.' for _,name,_,price in FRAMES]
    lines += ['', '## Баланс','', 'Названия зелий и свитков — заготовки наград, а не автоматически выданные способности. '
              'Версия правил, свойства, заряды, расходники и допустимость определяются мастером. '
              'Фамильяры — небольшие компаньоны, не способ получить мощное боевое существо.', '',
              'Ключи не продаются за реальные деньги и выдаются мастерами.']
    output=ROOT/'output/treasury_catalog.md';output.parent.mkdir(exist_ok=True)
    output.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(output)
